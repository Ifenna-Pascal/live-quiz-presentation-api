package routers

import (
	"fmt"
	"net/http"
	"slices"
	"strings"

	"github.com/gin-gonic/gin"
	swaggerFiles "github.com/swaggo/files"
	ginSwagger "github.com/swaggo/gin-swagger"
)

type Router interface {
	Serve()
}

type Route struct {
	Method      string
	Path        string
	Handle      gin.HandlerFunc
	MiddleWares gin.HandlersChain
}

type routing struct {
	address        string
	routers        []Route
	allowedOrigins []string
}

// NewRouting builds the HTTP server. allowedOrigins lists the websites
// (e.g. "https://app.example.com") whose pages may call the API; an empty
// list allows every website.
func NewRouting(address string, routers []Route, allowedOrigins []string) Router {
	return &routing{
		address:        address,
		routers:        routers,
		allowedOrigins: allowedOrigins,
	}
}

func (r *routing) Serve() {
	ginRouter := gin.New()
	ginRouter.Use(gin.Logger())
	ginRouter.Use(gin.Recovery())
	ginRouter.Use(CORSHandler(r.allowedOrigins))
	ginRouter.Handle(http.MethodGet, "/ping", HealthCheck)
	// Swagger UI: open /swagger/index.html in a browser. The UI page loads
	// /swagger/doc.json, which is the API description generated by `swag init`
	// into the docs package (imported in cmd/rest/main.go).
	ginRouter.GET("/swagger/*any", ginSwagger.WrapHandler(swaggerFiles.Handler))

	for _, router := range r.routers {
		if router.MiddleWares == nil {
			ginRouter.Handle(router.Method, router.Path, router.Handle)
		} else {
			var handlers []gin.HandlerFunc
			for _, middle := range router.MiddleWares {
				handlers = append(handlers, middle)
			}
			handlers = append(handlers, router.Handle)
			ginRouter.Handle(router.Method, router.Path, handlers...)
		}
	}

	ginRouter.NoMethod(NoMethodHandler)
	ginRouter.NoRoute(NoRouteHandler)
	err := ginRouter.Run(r.address)
	if err != nil {
		// panic stops the program immediately with an error message.
		panic(err)
	}
	fmt.Printf("started at %s", r.address)
	ginRouter.Run(r.address)
}

// CORSHandler lets web pages from other websites call the API.
//
// Before a browser sends a request with a JSON body or an Authorization
// header, it first sends an OPTIONS "preflight" request asking for
// permission. This middleware answers that request itself with 204 and the
// allowed methods and headers; without it the browser blocks the real call.
func CORSHandler(allowedOrigins []string) gin.HandlerFunc {
	return func(c *gin.Context) {
		origin := c.GetHeader("Origin")
		header := c.Writer.Header()

		if len(allowedOrigins) == 0 {
			// No list configured: any website may call the API.
			header.Set("Access-Control-Allow-Origin", "*")
		} else if slices.Contains(allowedOrigins, origin) {
			header.Set("Access-Control-Allow-Origin", origin)
			// The answer depends on the Origin, so caches must not reuse it
			// for a different website.
			header.Add("Vary", "Origin")
		}

		if c.Request.Method == http.MethodOptions {
			header.Set("Access-Control-Allow-Methods", strings.Join([]string{
				http.MethodGet, http.MethodPost, http.MethodPut, http.MethodDelete, http.MethodOptions,
			}, ", "))
			header.Set("Access-Control-Allow-Headers", "Content-Type, Authorization")
			// Let the browser remember the answer for 10 minutes.
			header.Set("Access-Control-Max-Age", "600")
			c.AbortWithStatus(http.StatusNoContent)
			return
		}
		// c.Next() says "I am done, continue to the next handler in the chain".
		c.Next()
	}
}
func NoMethodHandler(c *gin.Context) {
	// c.JSON(statusCode, data) writes a JSON response.
	// http.StatusMethodNotAllowed is the constant 405.
	// gin.H is a shortcut for map[string]any - a quick way to build a JSON
	// object: gin.H{"error": "x"} becomes {"error":"x"}.
	c.JSON(http.StatusMethodNotAllowed, gin.H{"error": "Specified HTTP method not allowed."})
}

func NoRouteHandler(c *gin.Context) {
	// http.StatusNotFound is 404.
	c.JSON(http.StatusNotFound, gin.H{"error": "Route not found."})
}

// HealthCheck godoc
//
//	@Summary	Health check
//	@Tags		health
//	@Produce	json
//	@Success	200	{object}	map[string]string
//	@Router		/ping [get]
func HealthCheck(c *gin.Context) {
	// http.StatusOK is 200.
	c.JSON(http.StatusOK, gin.H{
		"description": "The service is up and running",
	})
}
